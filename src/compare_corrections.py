"""Compare the original results with the post-freeze correction run.

Everything in the comparison is read from files: the original results in
aman/results (unchanged), the original inputs as committed at the reviewed
version, and the correction outputs. Nothing is typed in by hand.

Run from the repository root, after the correction run and evaluation:
    python aman/src/compare_corrections.py --corrections aman/results/corrections/2026-11-18
"""

import csv
import hashlib
import io
import json
import os
import subprocess
import sys

from output_paths import input_folder

HERE = os.path.dirname(os.path.abspath(__file__))
AMAN = os.path.abspath(os.path.join(HERE, ".."))
ORIGINAL = os.path.join(AMAN, "results")
REVIEWED_COMMIT = "d3c86de"          # the version reviewed on 17 November 2026
CORRECTIONS = input_folder("--corrections")
MODEL = os.path.join(CORRECTIONS, "model")
EVALUATION = os.path.join(CORRECTIONS, "evaluation")


def read_csv(path):
    with open(path, newline="") as file:
        return list(csv.DictReader(file))


def read_committed(path):
    text = subprocess.run(["git", "show", REVIEWED_COMMIT + ":aman/" + path], cwd=AMAN,
                          capture_output=True, text=True).stdout
    return list(csv.DictReader(io.StringIO(text)))


def file_hash(path):
    with open(path, "rb") as file:
        return hashlib.sha256(file.read()).hexdigest()


def table(rows, columns, headers=None):
    lines = ["| " + " | ".join(headers or columns) + " |", "|" + "---|" * len(columns)]
    for row in rows:
        lines.append("| " + " | ".join(str(row.get(c, "")) for c in columns) + " |")
    return "\n".join(lines)


page = ["# Before and after the post-freeze corrections of 18 November 2026", "",
        "Generated by `src/compare_corrections.py`. \"Original\" means the results reviewed at commit "
        "`" + REVIEWED_COMMIT + "` (the freeze of 17 November 2026 and the runs and evaluation made then). "
        "\"Corrected\" means the post-freeze correction run in this folder. The corrected run is not a new "
        "recommendation frozen before outcomes were seen.", ""]

#########1. The original freeze and evaluation are unchanged############

recorded = {}
with open(os.path.join(CORRECTIONS, "original_file_hashes.txt")) as file:
    for line in file:
        if line.strip() and not line.startswith("#"):
            digest, path = line.split()
            recorded[path] = digest
unchanged = [p for p, d in recorded.items() if file_hash(os.path.join(AMAN, p)) == d]
page += ["## 1. Original freeze and evaluation files", "",
         str(len(unchanged)) + " of " + str(len(recorded)) + " files under `results/freeze/` and `results/evaluation/` "
         "have the same SHA-256 as when they were checked before the corrections began.", ""]

#########2. Candidate eligibility############

old_pool = {r["player_id"]: r for r in read_committed("data/processed/pool_players.csv") if r["status"] == "C"}
new_pool = {r["player_id"]: r for r in read_csv(os.path.join(AMAN, "data", "processed", "pool_players.csv"))
            if r["status"] == "C"}
new_pool_by_name = {r["name"]: r for r in new_pool.values()}
existing = [r for r in read_csv(os.path.join(AMAN, "data", "processed", "pool_players.csv")) if r["status"] == "E"]
changes = []
for p in sorted(new_pool, key=lambda q: new_pool[q]["name"]):
    if old_pool[p]["two_year_status"] != new_pool[p]["two_year_status"]:
        changes.append({"player": new_pool[p]["name"], "club": new_pool[p]["club_name"],
                        "before": old_pool[p]["two_year_status"], "after": new_pool[p]["two_year_status"],
                        "evidence now": new_pool[p]["two_year_evidence"]})


def count(pool, status):
    return len([p for p in pool.values() if p["two_year_status"] == status])


page += ["## 2. Candidate eligibility under the two-year rule", "",
         table([{"status": s, "original": count(old_pool, s), "corrected": count(new_pool, s)}
                for s in ["eligible", "joined within two years", "not verified"]], ["status", "original", "corrected"]), "",
         str(len(changes)) + " candidates changed status. The reason in each case is how the start of the current spell "
         "is found: clubs are now identified by id, with a reviewed table of youth-side names "
         "(`docs/club_aliases.csv`), so Real Unión is no longer treated as part of Real Sociedad, and promotions from a "
         "club's own short-named youth side (for example FC Bayern II or RM Castilla) are no longer read as new signings.", "",
         table(changes, ["player", "club", "before", "after", "evidence now"]), ""]

#########3. Scoring reference############

with open(os.path.join(ORIGINAL, "freeze", "freeze_manifest.json")) as file:
    frozen_inputs = json.load(file)["input_sha256"]
same_scores = file_hash(os.path.join(AMAN, "data", "processed", "scores.csv")) == frozen_inputs["data/processed/scores.csv"]
same_roles = file_hash(os.path.join(AMAN, "data", "processed", "pool_roles.csv")) == frozen_inputs["data/processed/pool_roles.csv"]
page += ["## 3. Scoring reference and scores", "",
         "- Candidates in the scoring reference: " + str(len(old_pool)) + " before, " + str(len(new_pool)) + " after; "
         "existing players: " + str(len(existing)) + ".",
         "- `scores.csv` identical to the version recorded at the freeze: " + ("yes" if same_scores else "NO") + ".",
         "- `pool_roles.csv` identical to the version recorded at the freeze: " + ("yes" if same_roles else "NO") + ".", ""]

#########4. Base plan############


def plan_facts(folder):
    squad = read_csv(os.path.join(folder, "base", "squad.csv"))
    summary = {r["item"]: r["value"] for r in read_csv(os.path.join(folder, "base", "summary.csv"))}
    return squad, summary


old_squad, old_summary = plan_facts(ORIGINAL)
new_squad, new_summary = plan_facts(MODEL)


def names(squad, action):
    return ", ".join(r["name"] + " (" + r["role"] + ")" if r["role"] else r["name"] for r in squad if r["action"] == action)


def lineup(squad):
    parts = []
    for g in ["GK", "CB", "WB", "CM", "AM", "ST"]:
        parts.append(g + ": " + ", ".join(r["name"] for r in squad if r["starter"] == "1" and r["role"] == g))
    return "; ".join(parts)


items = [("Purchases", names(old_squad, "bought"), names(new_squad, "bought")),
         ("Sales", names(old_squad, "sold"), names(new_squad, "sold")),
         ("Starting eleven", lineup(old_squad), lineup(new_squad))]
for key, label in [("status", "Solver status"), ("optimality_gap", "Optimality gap"), ("objective", "Objective"),
                   ("purchase_fees", "Purchase fees, GBP m"), ("sale_receipts", "Sale receipts, GBP m"),
                   ("net_spend", "Net spend, GBP m"), ("wages", "Annual wages, GBP m"),
                   ("candidates_available", "Candidates available")]:
    items.append((label, old_summary.get(key, ""), new_summary.get(key, "")))
page += ["## 4. Base plan", "",
         table([{"item": a, "original": b, "corrected": c, "same": "yes" if b == c else "no"} for a, b, c in items],
               ["item", "original", "corrected", "same"]), ""]

# Reconcile the corrected base plan from its saved squad file, independently of the solver
bought = [r for r in new_squad if r["action"] == "bought"]
sold = [r for r in new_squad if r["action"] == "sold"]
squad = [r for r in new_squad if r["action"] in ("kept", "bought")]
fees = sum(float(r["fee_or_receipt_gbp_m"]) for r in bought)
receipts = sum(float(r["fee_or_receipt_gbp_m"]) for r in sold)
wages = sum(float(r["wage_gbp_m"]) for r in squad)
starters = {g: len([r for r in squad if r["starter"] == "1" and r["role"] == g]) for g in ["GK", "CB", "WB", "CM", "AM", "ST"]}
page += ["Recomputed from the saved squad file (rounded to two decimals per player): fees " + str(round(fees, 2))
         + ", receipts " + str(round(receipts, 2)) + ", net spend " + str(round(fees - receipts, 2))
         + " (limit 250), wages " + str(round(wages, 2)) + " (limit 148), arrivals " + str(len(bought))
         + " (limit 6), sales " + str(len(sold)) + " (limit 6), starters per role " + str(starters) + ".", ""]

#########5. All runs and alternatives############

old_runs = {r["run"]: r for r in read_csv(os.path.join(ORIGINAL, "runs_summary.csv"))}
new_runs = {r["run"]: r for r in read_csv(os.path.join(MODEL, "runs_summary.csv"))}
rows = []
for name in new_runs:
    o, n = old_runs.get(name, {}), new_runs[name]
    rows.append({"run": name, "objective before": o.get("objective", ""), "objective after": n["objective"],
                 "candidates before": o.get("candidates", ""), "candidates after": n["candidates"],
                 "same transfers": "yes" if (o.get("bought"), o.get("sold")) == (n["bought"], n["sold"]) else "no",
                 "same spend and wages": "yes" if (o.get("net_spend"), o.get("wages")) == (n["net_spend"], n["wages"]) else "no"})
differ = [r for r in rows if r["same transfers"] == "no" or r["objective before"] != r["objective after"]
          or r["same spend and wages"] == "no"]
identical = {}
for name in ["direct_alternatives.csv", "full_plan_alternatives.csv", "shortlist_review.csv"]:
    identical[name] = file_hash(os.path.join(ORIGINAL, name)) == file_hash(os.path.join(MODEL, name))
old_review = read_csv(os.path.join(ORIGINAL, "shortlist_review.csv"))
new_review = read_csv(os.path.join(MODEL, "shortlist_review.csv"))
review_columns = [c for c in old_review[0] if any(x[c] != y[c] for x, y in zip(old_review, new_review))]
review_rows = sum(1 for x, y in zip(old_review, new_review) if any(x[c] != y[c] for c in review_columns))
shortlist_status = [new_pool_by_name.get(r["player"], {}).get("two_year_status", "") for r in new_review]
page += ["## 5. Sensitivity runs and alternatives", "",
         "- Runs compared: " + str(len(rows)) + ". Runs whose transfers, objective, spend or wages changed: "
         + str(len(differ)) + ".",
         "- Every run now has more candidates available, because of the eligibility changes in Section 2; "
         "the run without the two-year rule is unaffected by them.",
         "- Direct alternatives identical to the original: " + ("yes" if identical["direct_alternatives.csv"] else "no") + ".",
         "- Alternative full plans identical to the original: " + ("yes" if identical["full_plan_alternatives.csv"] else "no") + ".",
         "- Shortlist review table identical to the original: " + ("yes" if identical["shortlist_review.csv"] else
             "no. Same players; " + str(review_rows) + " rows differ in the column(s) " + ", ".join(review_columns)
             + ", which repeat the spell evidence. For most the wording changed; for some the start date changed "
             "(for example a player now dated from joining the club's own youth side). Shortlisted players still "
             "eligible: " + str(shortlist_status.count("eligible")) + " of " + str(len(shortlist_status))
             + ". The frozen review itself is unchanged") + ".", ""]
if differ:
    page += [table(differ, ["run", "objective before", "objective after", "same transfers", "same spend and wages"]), ""]
page += ["<details><summary>All runs</summary>", "",
         table(rows, ["run", "objective before", "objective after", "candidates before", "candidates after",
                      "same transfers", "same spend and wages"]), "", "</details>", ""]

#########6. Evaluation############

old_summary = read_csv(os.path.join(ORIGINAL, "evaluation", "group_summary.csv"))
new_summary = read_csv(os.path.join(EVALUATION, "group_summary.csv"))
old_by = {r["group"]: r for r in old_summary}
eval_rows = []
for r in new_summary:
    if r["group"] == "all groups":
        continue
    old = old_by.get(r["group"], {})
    old_value = old.get("average_minutes_share") if r["measure"].startswith("share") else old.get("average_value_change_pct")
    eval_rows.append({"group": r["group"], "measure": r["measure"], "memberships": r["memberships"],
                      "valid": r["valid_observations"], "mean before": old_value, "mean after": r["mean"],
                      "median after (added after evaluation)": r["median_added_after_evaluation"]})
totals = [r for r in new_summary if r["group"] == "all groups"][0]

old_players = read_csv(os.path.join(ORIGINAL, "evaluation", "player_outcomes.csv"))
new_players = read_csv(os.path.join(EVALUATION, "player_outcomes.csv"))
share_before = {(r["group"], r["player"]): r["minutes_share"] for r in old_players}
moved = []
for r in new_players:
    before = share_before.get((r["group"], r["player"]), "")
    after = r["share_of_main_club_league_minutes"]
    # The original file rounded to three decimals, the corrected one to four
    if before != "" and after != "" and abs(float(before) - float(after)) > 0.001:
        moved.append({"group": r["group"], "player": r["player"], "main club": r["main_club"],
                      "share before": before, "share after": after,
                      "season minutes, all clubs": r["season_league_minutes_all_clubs"]})
page += ["## 6. Evaluation on 2025/26", "",
         "The original evaluation divided a player's minutes for all clubs by the matches of one club. The corrected "
         "evaluation measures each club separately and summarises each player at the club where he or she played the "
         "most league minutes. Means and counts are the summaries named in the frozen evaluation plan; medians were "
         "added after the evaluation and are labelled as such.", "",
         "Group memberships: " + totals["memberships"] + "; distinct players: " + totals["distinct_players"] + ".", "",
         table(eval_rows, ["group", "measure", "memberships", "valid", "mean before", "mean after",
                           "median after (added after evaluation)"]), "",
         "The original group summary also averaged goals plus assists per 90 across roles. That figure is no longer "
         "reported, because it mixes roles where it means different things.", "",
         "Players whose playing-time share changed (all played for two clubs):", "",
         table(moved, ["group", "player", "main club", "share before", "share after", "season minutes, all clubs"]), ""]

