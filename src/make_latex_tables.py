def timing(date, text, url):
    """When a source was published relative to the cutoff of 31 May 2025."""
    if date:
        return ("before, " if date <= "2025-05-31" else "after, ") + date
    later_words = ("later", "after the cutoff", "2026")
    if any(word in text for word in later_words) or "/2025/7/" in url or "072025" in url:
        return "after, undated"
    return "date not recorded"


