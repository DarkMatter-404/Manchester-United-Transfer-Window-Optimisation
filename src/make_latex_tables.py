def tex(text):
    """Escape the characters that LaTeX treats as commands."""
    text = str(text)
    for old, new in SPELLING.items():
        text = text.replace(old, new)
    for old, new in [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"),
                     ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}")]:
        text = text.replace(old, new)
    return text


def number(value, digits=1, sign=False, thousands=False):
    """A number for a table cell, with a true minus sign."""
    value = float(value)
    if thousands:
        text = "{:,.{d}f}".format(abs(value), d=digits)
    else:
        text = "{:.{d}f}".format(abs(value), d=digits)
    if float(text.replace(",", "")) == 0:
        return text
    if value < 0:
        return "$-$" + text
    if sign:
        return "$+$" + text
    return text


def write(name, lines):
    with open(os.path.join(OUT, name + ".tex"), "w") as file:
        file.write("% Generated by src/make_latex_tables.py from the saved outputs. Do not edit by hand.\n")
        file.write("\n".join(lines) + "\n")
    print("wrote", name + ".tex")


def row(cells):
    return " & ".join(cells) + " \\\\"


def write_data(name, columns, rows):
    """A whitespace-separated data file for pgfplots, with a header line."""
    with open(os.path.join(OUT, name), "w") as file:
        file.write(" ".join(columns) + "\n")
        for values in rows:
            file.write(" ".join(str(v) for v in values) + "\n")
    print("wrote", name)


